// Build `src/lib/geo/worldDots.ts`: the land mask the dashboard's region map
// draws as a grid of dots.
//
// Generated rather than hand-written because it is data about coastlines, and
// generated rather than shipped as a library because the map needs a few
// kilobytes of "is there land here", not a projection engine (DECISIONS.md
// §113). The source is Natural Earth's 1:110m land polygons, which are in the
// public domain, by way of the `world-atlas` package.
//
// The three packages it needs are deliberately not dependencies of the app.
// Run it from a scratch directory that has them:
//
//   npm i world-atlas@2 topojson-client@3 d3-geo@3
//   node /path/to/apps/web/scripts/build-world-dots.mjs > /path/to/apps/web/src/lib/geo/worldDots.ts

import { createRequire } from "node:module";

const require = createRequire(`${process.cwd()}/`);
const { feature } = require("topojson-client");
const { geoContains } = require("d3-geo");
const land = feature(require("world-atlas/land-110m.json"), "land");

// Two degrees a cell. North of 82° is ice and south of 56° is Antarctica, and
// neither is anywhere a cloud has a region; dropping them keeps the map's
// aspect close to the populated world rather than the whole sphere.
const STEP = 2;
const NORTH = 82;
const SOUTH = -56;
const WEST = -180;
const COLUMNS = 360 / STEP;
const ROWS = (NORTH - SOUTH) / STEP;

// A cell is land when at least two of nine points inside it are, so a thin
// coast or an island the size of Great Britain still draws, and a cell that
// only grazes a shoreline does not.
const SAMPLES = [1 / 6, 1 / 2, 5 / 6];

const rows = [];
for (let row = 0; row < ROWS; row += 1) {
  let bits = "";
  for (let column = 0; column < COLUMNS; column += 1) {
    let hits = 0;
    for (const dy of SAMPLES) {
      for (const dx of SAMPLES) {
        const lon = WEST + (column + dx) * STEP;
        const lat = NORTH - (row + dy) * STEP;
        if (geoContains(land, [lon, lat])) hits += 1;
      }
    }
    bits += hits >= 2 ? "1" : "0";
  }
  let hex = "";
  for (let i = 0; i < bits.length; i += 4) {
    hex += Number.parseInt(bits.slice(i, i + 4).padEnd(4, "0"), 2).toString(16);
  }
  rows.push(hex);
}

process.stdout.write(`// Generated by scripts/build-world-dots.mjs from Natural Earth 1:110m land
// (public domain). Edit the script, not this file.

/** Degrees per cell, and the edges of the grid. */
export const WORLD_GRID = {
  step: ${STEP},
  north: ${NORTH},
  south: ${SOUTH},
  west: ${WEST},
  columns: ${COLUMNS},
  rows: ${ROWS},
} as const;

/** One hex string per row, north first; each bit is one cell, west first. */
export const WORLD_LAND: readonly string[] = [
${rows.map((hex) => `  "${hex}",`).join("\n")}
];
`);
